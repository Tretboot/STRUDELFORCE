#!/usr/bin/env python3
"""level_tool.py - STRUDELFORCE level pipeline (levels/levels.json is the single source of truth)

  level_tool.py validate              # row sizes, legend, exits open, BFS exit connectivity
  level_tool.py header  src/level_data.h
  level_tool.py rogue   <seed> <biome> <len>   # mirror of rl_build() in level_data.h
  level_tool.py png     <outdir>      # voxel-shaded previews: chunk sheet, every level, 3 roguelike runs
"""
import sys, os, json, zlib, struct
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "..", "levels", "levels.json")
SOLID = set("#BMO?=")          # blocks movement (bonus/pipe/belt are solid blocks)
HAZARD = set("^")

def load(): return json.load(open(DB))

# ------------------------------------------------------------ validate
def validate(db):
    errs = []; W, H = db["chunk_w"], db["chunk_h"]; ids = set()
    for c in db["chunks"]:
        cid = c["id"]
        if cid in ids: errs.append("%s: duplicate id" % cid)
        ids.add(cid); rows = c["rows"]
        if len(rows) != H: errs.append("%s: %d rows" % (cid, len(rows)))
        for y, r in enumerate(rows):
            if len(r) != W: errs.append("%s row %d: len %d" % (cid, y, len(r)))
            for ch in r:
                if ch not in db["legend"]: errs.append("%s row %d: unknown tile %r" % (cid, y, ch))
        ex = c["exits"]
        cells = {}
        if "l" in ex: cells["l"] = (0, ex["l"])
        if "r" in ex: cells["r"] = (W - 1, ex["r"])
        if "u" in ex: cells["u"] = (ex["u"], 0)
        if "d" in ex: cells["d"] = (ex["d"], H - 1)
        for k, (x, y) in cells.items():
            if 0 <= y < len(rows) and 0 <= x < len(rows[y]) and rows[y][x] in SOLID:
                errs.append("%s: exit %s blocked at (%d,%d)" % (cid, k, x, y))
        if len(cells) >= 2:
            start = list(cells.values())[0]; seen = {start}; q = deque([start])
            while q:
                x, y = q.popleft()
                for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                    nx, ny = x+dx, y+dy
                    if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and rows[ny][nx] not in SOLID:
                        seen.add((nx, ny)); q.append((nx, ny))
            for k, p in cells.items():
                if p not in seen: errs.append("%s: exit %s unreachable" % (cid, k))
    byid = {c["id"]: c for c in db["chunks"]}
    for lv in db["levels"]:
        prev = None
        for s in lv["seq"]:
            if s not in byid: errs.append("level %s: unknown chunk %s" % (lv["name"], s)); continue
            c = byid[s]
            if not (c["biome_mask"] >> lv["biome"]) & 1: errs.append("level %s: %s not allowed in biome %d" % (lv["name"], s, lv["biome"]))
            if prev and prev["exits"].get("r") != c["exits"].get("l"):
                errs.append("level %s: seam %s->%s r=%s l=%s" % (lv["name"], prev["id"], s, prev["exits"].get("r"), c["exits"].get("l")))
            prev = c
    return errs

# ------------------------------------------------------------ roguelike (mirror of C)
def xorshift(s):
    s ^= (s << 13) & 0xFFFFFFFF; s ^= s >> 17; s ^= (s << 5) & 0xFFFFFFFF
    return s & 0xFFFFFFFF

def rl_build(db, seed, biome, length):
    ch = db["chunks"]; n_ch = len(ch)
    start = next(i for i, c in enumerate(ch) if "start" in c["flags"])
    arena = next(i for i, c in enumerate(ch) if "arena" in c["flags"])
    length = max(2, min(24, length)); seed = seed or 0x5F0CE
    out = [start]; prev = start; chest = 0
    while len(out) < length - 1:
        k = start
        for _ in range(32):
            seed = xorshift(seed); k = seed % n_ch; b = ch[k]; a = ch[prev]
            if "arena" in b["flags"] or "start" in b["flags"]: continue
            if "chest" in b["flags"] and chest: continue
            if not (b["biome_mask"] >> biome) & 1: continue
            if a["exits"].get("r", 255) == 255 or a["exits"].get("r") != b["exits"].get("l"): continue
            if b["difficulty"] > 2 + len(out) // 2: continue
            if k == prev: continue
            break
        else:
            k = start
            for j, b in enumerate(ch):     # deterministic fallback: first legal chunk
                if "arena" in b["flags"] or "start" in b["flags"] or j == prev: continue
                if ("chest" in b["flags"] and chest) or not (b["biome_mask"] >> biome) & 1: continue
                if ch[prev]["exits"].get("r") != b["exits"].get("l"): continue
                k = j; break
        if "chest" in ch[k]["flags"]: chest = 1
        out.append(k); prev = k
    out.append(arena)
    return out

# ------------------------------------------------------------ header generator
def gen_header(db):
    F = {"arena": 1, "chest": 4, "start": 8, "end": 16}
    L = ["/* level_data.h - GENERATED by tools/level_tool.py from levels/levels.json. DO NOT EDIT. */",
         "#ifndef LEVEL_DATA_H", "#define LEVEL_DATA_H", "#include <stdint.h>",
         "#define LV_CHUNK_W %d" % db["chunk_w"], "#define LV_CHUNK_H %d" % db["chunk_h"], "#define LV_MAX_CHUNKS 24",
         "#define LV_EXIT_NONE 255",
         "#define LV_F_ARENA 1", "#define LV_F_CHEST 4", "#define LV_F_START 8", "#define LV_F_END 16",
         "typedef struct { const char *id; const char *rows[LV_CHUNK_H];",
         "                 uint8_t exit_l, exit_r, exit_u, exit_d, difficulty, biome_mask, flags; } LvChunk;",
         "typedef struct { const char *name; uint8_t biome, palette, vertical, music_type; const char *music_file;",
         "                 uint8_t music_subsong, n_chunks; const uint8_t *seq; uint16_t time_limit; } LvLevel;",
         "enum { LV_MUSIC_STRUDEL = 0, LV_MUSIC_TFMX = 1, LV_MUSIC_MOD = 2, LV_MUSIC_SID = 3 };",
         "static const LvChunk LV_CHUNKS[] = {"]
    idx = {}
    for i, c in enumerate(db["chunks"]):
        idx[c["id"]] = i; e = c["exits"]
        rows = ",".join('"%s"' % r for r in c["rows"])
        fl = sum(F[f] for f in c["flags"])
        L.append(' {"%s", {%s}, %d,%d,%d,%d, %d,%d,%d},' % (c["id"], rows, e.get("l",255), e.get("r",255), e.get("u",255), e.get("d",255),
                                                         c["difficulty"], c["biome_mask"], fl))
    L.append("};")
    L.append("#define LV_NUM_CHUNKS %d" % len(db["chunks"]))
    MT = {"strudel": 0, "tfmx": 1, "mod": 2, "sid": 3}
    for j, lv in enumerate(db["levels"]):
        L.append("static const uint8_t LV_SEQ_%d[] = {%s};" % (j, ",".join(str(idx[s]) for s in lv["seq"])))
    L.append("static const LvLevel LV_LEVELS[] = {")
    for j, lv in enumerate(db["levels"]):
        mu = lv["music"]
        L.append(' {"%s", %d, %d, %d, %d, "%s", %d, %d, LV_SEQ_%d, %d},' % (lv["name"], lv["biome"], lv["palette"], int(lv["vertical"]),
                 MT[mu["type"]], mu["file"].replace("\\", "/"), mu.get("subsong", 0), len(lv["seq"]), j, lv["time_limit"]))
    L.append("};")
    L.append("#define LV_NUM_LEVELS %d" % len(db["levels"]))
    L += ["/* Roguelike assembler - deterministic (Xorshift32). Mirror: tools/level_tool.py rl_build() */",
          "static uint32_t lv_xorshift(uint32_t *s) { uint32_t x = *s; x ^= x << 13; x ^= x >> 17; x ^= x << 5; *s = x; return x; }",
          "static int lv_find_flag(uint8_t f) { int i; for (i = 0; i < LV_NUM_CHUNKS; i++) if (LV_CHUNKS[i].flags & f) return i; return 0; }",
          "static int lv_rl_build(uint32_t seed, uint8_t biome, int len, uint8_t *out) {",
          "    int n = 0, prev, k, tries, chest = 0, start = lv_find_flag(LV_F_START), arena = lv_find_flag(LV_F_ARENA);",
          "    if (len < 2) len = 2;", "    if (len > LV_MAX_CHUNKS) len = LV_MAX_CHUNKS;", "    if (!seed) seed = 0x5F0CEu;",
          "    out[n++] = (uint8_t)start; prev = start;",
          "    while (n < len - 1) {",
          "        k = start;",
          "        for (tries = 0; tries < 32; tries++) {",
          "            const LvChunk *a = &LV_CHUNKS[prev], *b;",
          "            k = (int)(lv_xorshift(&seed) % (uint32_t)LV_NUM_CHUNKS); b = &LV_CHUNKS[k];",
          "            if (b->flags & (LV_F_ARENA | LV_F_START)) continue;",
          "            if ((b->flags & LV_F_CHEST) && chest) continue;",
          "            if (!((b->biome_mask >> biome) & 1)) continue;",
          "            if (a->exit_r == LV_EXIT_NONE || a->exit_r != b->exit_l) continue;",
          "            if (b->difficulty > 2 + n / 2) continue;",
          "            if (k == prev) continue;",
          "            break;",
          "        }",
          "        if (tries == 32) {",
          "            int j; k = start;",
          "            for (j = 0; j < LV_NUM_CHUNKS; j++) {",
          "                const LvChunk *b = &LV_CHUNKS[j];",
          "                if ((b->flags & (LV_F_ARENA | LV_F_START)) || j == prev) continue;",
          "                if (((b->flags & LV_F_CHEST) && chest) || !((b->biome_mask >> biome) & 1)) continue;",
          "                if (LV_CHUNKS[prev].exit_r != b->exit_l) continue;",
          "                k = j; break;",
          "            }",
          "        }",
          "        if (LV_CHUNKS[k].flags & LV_F_CHEST) chest = 1;",
          "        out[n++] = (uint8_t)k; prev = k;",
          "    }",
          "    out[n++] = (uint8_t)arena;",
          "    return n;", "}", "#endif", ""]
    return "\n".join(L)

# ------------------------------------------------------------ PNG
def hexrgb(h): return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16))
def shade(c, f): return tuple(max(0, min(255, int(v * f))) for v in c)

def write_png(path, w, h, px):
    raw = b"".join(b"\0" + bytes(px[y*w*3:(y+1)*w*3]) for y in range(h))
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) +
                chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))

def tile_color(ch, pal):
    if ch in "#B": return hexrgb(pal["solid"])
    if ch in "M=O": return shade(hexrgb(pal["solid"]), 0.8)
    if ch in "?D*U": return hexrgb(pal["item"])
    if ch == "C": return hexrgb(pal["accent"])
    if ch in "^": return hexrgb(pal["hazard"])
    if ch in "wfto": return hexrgb(pal["enemy"])
    if ch == "G": return hexrgb(pal["hazard"])
    if ch in "-HS": return hexrgb(pal["accent"])
    if ch == "E": return (255, 255, 255)
    if ch == "P": return (80, 255, 80)
    return None

def render_strip(db, chunk_ids, pal, T=8):
    W, H = db["chunk_w"], db["chunk_h"]; byid = {c["id"]: c for c in db["chunks"]}
    tw, th = W * len(chunk_ids), H
    w, h = tw * T + 4, th * T + 4
    px = bytearray(w * h * 3)
    sky = [hexrgb(c) for c in pal["sky"]]
    for y in range(h):                                   # copper bands
        band = sky[min(len(sky) - 1, y * len(sky) // h)]
        if (y // 2) % 2: band = shade(band, 1.08)
        for x in range(w): px[(y*w+x)*3:(y*w+x)*3+3] = bytes(band)
    def put(x, y, c):
        if 0 <= x < w and 0 <= y < h: px[(y*w+x)*3:(y*w+x)*3+3] = bytes(c)
    grid = []
    for cid in chunk_ids: grid.append(byid[cid]["rows"])
    for y in range(th):
        for ci, rows in enumerate(grid):
            for x in range(W):
                ch = rows[y][x]
                gx = ci * W + x
                if ch == "~":
                    wc = hexrgb(pal["water"])
                    for yy in range(T):
                        for xx in range(T):
                            put(gx*T+xx, y*T+yy, shade(wc, 0.9 if (xx + yy + y) % 4 else 1.15))
                    continue
                c = tile_color(ch, pal)
                if c is None: continue
                solid = ch in SOLID
                d = 3 if solid else 2                       # voxel extrusion depth (2.5D)
                for k in range(d, 0, -1):                   # side faces: shifted, darkened (no textures!)
                    for yy in range(T):
                        put(gx*T + T - 1 + k, y*T + yy + k, shade(c, 0.45))
                    for xx in range(T):
                        put(gx*T + xx + k, y*T + T - 1 + k, shade(c, 0.35))
                small = 0 if solid else 1
                for yy in range(small, T - small):
                    for xx in range(small, T - small):
                        f = 1.25 if yy == small else (0.85 if xx == T - 1 - small else 1.0)  # top light / AO edge
                        put(gx*T+xx, y*T+yy, shade(c, f))
    return w, h, px

def png_all(db, outdir):
    os.makedirs(outdir, exist_ok=True); made = []
    pals = db["palettes"]
    ids = [c["id"] for c in db["chunks"]]
    for start in range(0, len(ids), 6):                  # chunk sheets
        sel = ids[start:start+6]
        w, h, px = render_strip(db, sel, pals[3])
        p = os.path.join(outdir, "chunks_%02d.png" % (start // 6)); write_png(p, w, h, px); made.append(p)
    for j, lv in enumerate(db["levels"]):
        w, h, px = render_strip(db, lv["seq"], pals[lv["palette"]])
        p = os.path.join(outdir, "level_%d_%s.png" % (j, lv["name"].split(" (")[0].lower().replace(" ", "_")))
        write_png(p, w, h, px); made.append(p)
    for seed, biome in ((1, 3), (1337, 2), (0xC0FFEE, 1)):
        seq = [db["chunks"][k]["id"] for k in rl_build(db, seed, biome, 8)]
        w, h, px = render_strip(db, seq, pals[biome])
        p = os.path.join(outdir, "rogue_seed%d_biome%d.png" % (seed, biome)); write_png(p, w, h, px); made.append(p)
    return made

if __name__ == "__main__":
    a = sys.argv[1:]; db = load()
    if not a: print(__doc__)
    elif a[0] == "validate":
        e = validate(db)
        for x in e: print("  ERR", x)
        print("LEVELS chunks=%d levels=%d errors=%d" % (len(db["chunks"]), len(db["levels"]), len(e))); sys.exit(1 if e else 0)
    elif a[0] == "header": open(a[1], "w").write(gen_header(db)); print("wrote", a[1])
    elif a[0] == "rogue":
        seq = rl_build(db, int(a[1], 0), int(a[2]), int(a[3])); print(seq, [db["chunks"][k]["id"] for k in seq])
    elif a[0] == "png":
        for p in png_all(db, a[1]): print("png", p)
