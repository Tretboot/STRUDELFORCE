#!/usr/bin/env python3
"""
STRUDELFORCE Asset Packer
Packt JSON/Audio-Assets in assets.dat und generiert src/assets_index.h
"""
import os, struct, zlib

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS_DIR = os.path.join(ROOT_DIR, "assets")
OUTPUT_FILE = os.path.join(ROOT_DIR, "assets.dat")
INDEX_FILE = os.path.join(ROOT_DIR, "src", "assets_index.h")

def pack_assets():
    asset_files = []
    for root, dirs, files in os.walk(ASSETS_DIR):
        for fn in sorted(files):
            if fn.endswith(('.dat', '.mod', '.tfmx', '.wav', '.json')):
                fp = os.path.join(root, fn)
                rp = os.path.relpath(fp, ASSETS_DIR).replace('\\', '/')
                with open(fp, 'rb') as f:
                    data = f.read()
                comp = zlib.compress(data, 9)
                if len(comp) >= len(data):
                    comp = b'\x00' + data
                else:
                    comp = b'\x01' + struct.pack('>I', len(data)) + comp
                asset_files.append({'name': rp, 'data': data, 'comp': comp})
                print(f"  [OK] {rp}: {len(data)} -> {len(comp)} B")
    
    blob = bytearray(b'SFAS' + struct.pack('>HI', 1, len(asset_files)))
    entries = []
    for a in asset_files:
        nb = a['name'].encode('utf-8')
        entries.append({'name': a['name'], 'offset': len(blob)})
        blob.extend(struct.pack('>H', len(nb)) + nb + a['comp'])
    
    with open(OUTPUT_FILE, 'wb') as f:
        f.write(blob)
    print(f"\nBlob: {OUTPUT_FILE} ({len(blob)} Bytes, {len(asset_files)} Dateien)")
    
    with open(INDEX_FILE, 'w', encoding='utf-8') as f:
        f.write("/* Generated by tools/asset_packer.py - DO NOT EDIT */\n")
        f.write("#ifndef ASSETS_INDEX_H\n#define ASSETS_INDEX_H\n#include <stdint.h>\n\n")
        f.write(f"#define ASSET_COUNT {len(asset_files)}\n\n")
        f.write("typedef enum {\n")
        for i, e in enumerate(entries):
            cn = e['name'].replace('.', '_').replace('/', '_').replace('-', '_').upper()
            f.write(f"    ASSET_{cn} = {i},\n")
        f.write("    ASSET_COUNT_ENUM\n} AssetID;\n\n")
        f.write("extern const uint8_t *asset_blob;\n")
        f.write("extern uint32_t asset_blob_size;\n\n")
        f.write("const uint8_t *asset_get(AssetID id, uint32_t *out_size);\n")
        f.write("#endif /* ASSETS_INDEX_H */\n")
    print(f"Index: {INDEX_FILE}")
    return len(asset_files)

if __name__ == "__main__":
    print("=" * 60 + "\nSTRUDELFORCE ASSET PACKER\n" + "=" * 60)
    print(f"{pack_assets()} Assets gepackt\n" + "=" * 60)

