#!/usr/bin/env python3
"""
STRUDELFORCE Localization Builder
Generiert src/localization.h aus assets/lang.json
"""
import json, os, sys

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG_FILE = os.path.join(ROOT_DIR, "assets", "lang.json")
OUTPUT_FILE = os.path.join(ROOT_DIR, "src", "localization.h")

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def build():
    if not os.path.exists(LANG_FILE):
        print(f"[ERROR] {LANG_FILE} fehlt!")
        return 1
    with open(LANG_FILE, 'r', encoding='utf-8') as f:
        d = json.load(f)
    texts, langs, deflang = d['texts'], d['languages'], d['default_language']
    tids = sorted(texts.keys())
    
    lines = [
        "/* Generated by tools/build_lang.py - DO NOT EDIT */",
        "#ifndef LOCALIZATION_H",
        "#define LOCALIZATION_H",
        "#include <stdint.h>",
        "",
        "extern uint8_t current_language;",
        "typedef enum {"
    ]
    for i, l in enumerate(langs):
        lines.append(f"    LANG_{l.upper()} = {i},")
    lines.append("    LANG_COUNT")
    lines.append("} LanguageID;\n")
    
    lines.append("typedef enum {")
    for i, t in enumerate(tids):
        lines.append(f"    {t} = {i},")
    lines.append("    TEXT_COUNT")
    lines.append("} TextID;\n")
    
    for lang in langs:
        lines.append(f"static const char *tbl_{lang}[TEXT_COUNT] = {{")
        for t in tids:
            txt = texts[t].get(lang, texts[t].get(deflang, ""))
            lines.append(f'    "{esc(txt)}",')
        lines.append("};\n")
    
    lines.append("static inline const char *get_text(TextID id) {")
    lines.append("    if (id >= TEXT_COUNT) return \"\";")
    lines.append("    switch (current_language) {")
    for lang in langs:
        lines.append(f"        case LANG_{lang.upper()}: return tbl_{lang}[id];")
    lines.append(f"        default: return tbl_{deflang}[id];")
    lines.append("    }")
    lines.append("}\n")
    lines.append("void set_language(LanguageID lang);")
    lines.append("void localization_init(void);\n")
    lines.append("#endif /* LOCALIZATION_H */\n")
    
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f"[OK] {OUTPUT_FILE} ({len(tids)} texts, {len(langs)} langs)")
    return 0

if __name__ == "__main__":
    print("=" * 60 + "\nSTRUDELFORCE LOCALIZATION BUILDER\n" + "=" * 60)
    sys.exit(build())
